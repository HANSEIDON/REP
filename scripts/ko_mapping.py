def main():
    with open(SRC, "r", encoding="utf-8") as f:
        data = json.load(f)

    src_ids = [ex["id"] for ex in data["exercises"]]
    missing = [i for i in src_ids if i not in KO]
    extra = [i for i in KO if i not in src_ids]
    if missing or extra:
        print("MISMATCH")
        print("missing:", missing)
        print("extra:", extra)
        return 1

    out = {
        "source": "MarvinNazari/exercise-images (CC0)",
        "count": len(src_ids),
        "exercises": [
            {
                "id": ex["id"],
                "name": ex["name"],
                "nameKo": KO[ex["id"]],
                "aliases": ex.get("aliases", []),
                "equipment": ex.get("equipment", []),
                "equipmentLabel": ex.get("equipmentLabel", ""),
                "muscles": ex.get("muscles", {}),
                "movementPattern": ex.get("movementPattern", ""),
                "category": ex.get("category", ""),
                "unilateral": ex.get("unilateral", False),
                "level": ex.get("level", ""),
                "view": ex.get("view", "side"),
                "frames": ex.get("frames", []),
                "images": ex.get("images", {}),
            }
            for ex in data["exercises"]
        ],
    }

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False)

    print(f"OK: {len(src_ids)} exercises -> {os.path.relpath(OUT, ROOT)}")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
